export type ApiErrorCode = keyof typeof errorMessages;

/** رسالة لرمز غير معروف (أضافه الباك ولم يُضف هنا بعد): لا تنهار الشاشة. */
export const fallbackErrorMessage = "تعذّر تنفيذ الطلب. أعد المحاولة، وإن استمرت المشكلة تواصل مع قسم IT.";

export function isApiErrorCode(code: string): code is ApiErrorCode {
  return Object.hasOwn(errorMessages, code);
}

/** النص العربي لرمز خطأ. يقبل أي نص لأن الرمز يصل من الشبكة. */
export function errorMessage(code: string): string {
  return isApiErrorCode(code) ? errorMessages[code] : fallbackErrorMessage;
}
